const namespace = "starwarsffg";
const action = "rulesReference";
const dialogId = "starwarsffg-rules-reference";

function element(tag, text) {
  const node = document.createElement(tag);
  if (text !== undefined) node.textContent = text;
  return node;
}

async function linkSource(citation, pages) {
  if (!game.modules.get("starwars-ffg-compendium-rus")?.active) return;
  const firstPage = parseInt(pages, 10);
  const editor = foundry.applications.ux.TextEditor.implementation;
  const html = await editor.enrichHTML(`@SWFFGPage[${firstPage}]`);
  const anchor = new DOMParser().parseFromString(html, "text/html").querySelector("a[href]");
  if (!anchor) return;
  const link = element("a", citation.textContent);
  link.href = anchor.getAttribute("href");
  link.target = "_blank";
  link.rel = "noopener noreferrer";
  citation.replaceChildren(link);
}

function renderRuleLabel(label) {
  const term = element("dt");
  let offset = 0;
  for (const match of label.matchAll(/:(success|failure|advantage|threat|triumph|despair|light|dark):/g)) {
    const icon = createResultIcon(match[1]);
    icon.classList.add("reference-result-icon");
    icon.setAttribute("aria-hidden", "true");
    term.append(label.slice(offset, match.index), icon);
    offset = match.index + match[0].length;
  }
  term.append(label.slice(offset));
  return term;
}

function renderTopic(content, groups) {
  content.replaceChildren();
  for (const [heading, pages, entries] of groups) {
    const section = element("section");
    const citation = element("small", "«Сила и судьба», с. " + pages);
    section.append(element("h3", heading), citation);
    linkSource(citation, pages).catch(error => console.warn("StarWarsFFG | Ошибка ссылки на книгу", error));
    const list = element("dl");
    for (const [name, description] of entries) {
      list.append(renderRuleLabel(name), element("dd", description));
    }
    section.append(list);
    content.append(section);
  }
  content.scrollTop = 0;
}

function showReference() {
  if (document.getElementById(dialogId)?.open) return true;
  const dialog = element("dialog");
  dialog.id = dialogId;
  dialog.setAttribute("aria-label", "Справка по правилам");
  const header = element("header");
  const close = element("button", "Закрыть");
  close.type = "button";
  close.addEventListener("click", () => dialog.close());
  header.append(element("h2", "Справка по правилам"), close);
  const nav = element("nav");
  nav.setAttribute("aria-label", "Разделы справки");
  const content = element("article");
  content.tabIndex = 0;
  for (const [index, [name, groups]] of sections.entries()) {
    const button = element("button", name);
    button.type = "button";
    button.setAttribute("aria-pressed", String(index === 0));
    button.addEventListener("click", () => {
      for (const other of nav.children) other.setAttribute("aria-pressed", String(other === button));
      renderTopic(content, groups);
    });
    nav.append(button);
  }
  renderTopic(content, sections[0][1]);
  dialog.append(header, nav, content);
  dialog.addEventListener("close", () => dialog.remove(), {once: true});
  dialog.addEventListener("keydown", event => {
    // Stop Foundry's global Escape shortcuts from acting on the canvas under the dialog.
    if (event.key === "Escape") {
      event.preventDefault();
      event.stopPropagation();
      dialog.close();
    }
  });
  document.body.append(dialog);
  dialog.showModal();
  return true;
}

Hooks.once("init", () => {
  game.keybindings.register(namespace, action, {
    name: "Справка по правилам",
    editable: [{key: "F1"}],
    precedence: CONST.KEYBINDING_PRECEDENCE.PRIORITY,
    repeat: true,
    onDown: context => context?.repeat || showReference(),
    restricted: false
  });
});

Hooks.once("ready", () => {
  // Foundry intentionally ignores keybindings while composing a chat message or editing a sheet.
  // Keep plain F1 available there only while the user has it assigned to the reference.
  window.addEventListener("keydown", event => {
    if (event.code !== "F1" || event.altKey || event.ctrlKey || event.metaKey || event.shiftKey ||
        event.isComposing || event.defaultPrevented || !game.keyboard.hasFocus) return;
    const bindings = game.keybindings.get(namespace, action);
    if (!bindings.some(binding => binding.key === "F1" && !binding.modifiers?.length)) return;
    event.preventDefault();
    event.stopPropagation();
    if (!event.repeat) showReference();
  }, {capture: true});
});
